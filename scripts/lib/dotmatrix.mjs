export const CELL_W = 5;
export const CELL_H = 7;

export function supports(ch) {
  return Object.hasOwn(G, ch);
}

// Lit dot centres for a line of text, in dot coordinates (column, row).
// Cells are CELL_W wide with one dark column between them.
export function litDots(str, col0 = 0, row0 = 0) {
  const dots = [];
  [...str].forEach((ch, i) => {
    const g = G[ch];
    if (!g) throw new Error(`dot-matrix font has no ${JSON.stringify(ch)} (text: ${JSON.stringify(str)})`);
    g.forEach((row, r) => {
      for (let c = 0; c < CELL_W; c++) if (row[c] === '#') dots.push([col0 + i * (CELL_W + 1) + c, row0 + r]);
    });
  });
  return dots;
}

// All lit dots as one path of circular arcs, written with relative moves so it stays small.
// (x0, y0) is the centre of dot (0, 0); pitch is the distance between dot centres.
export function dotsPath(dots, { x0, y0, pitch, r }) {
  const sorted = [...dots].sort((a, b) => a[1] - b[1] || a[0] - b[0]);
  let d = '';
  let px = 0;
  let py = 0;
  const R = fmt(r);
  const D = fmt(2 * r);
  sorted.forEach(([c, rw], i) => {
    const x = x0 + c * pitch - r;
    const y = y0 + rw * pitch;
    if (i === 0) d += `M${fmt(x)} ${fmt(y)}`;
    else {
      const dx = fmt(x - px);
      const dy = fmt(y - py);
      d += `m${dx}${dy.startsWith('-') ? '' : ' '}${dy}`;
    }
    d += `a${R} ${R} 0 1 0 ${D} 0a${R} ${R} 0 1 0-${D} 0`;
    px = x;
    py = y;
  });
  return d;
}
